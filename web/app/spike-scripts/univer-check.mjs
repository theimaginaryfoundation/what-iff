import fs from 'node:fs';
import { chromium } from 'playwright';
import { serve } from './serve.mjs';
import { toUniver, fromUniver } from './xlsx-univer.mjs';
import ExcelJS from 'exceljs';
const here = new URL('.', import.meta.url).pathname;
const data = await toUniver(fs.readFileSync(here + 'sample.xlsx'));
console.log('toUniver sheets:', data.sheetOrder.length, 'styles:', Object.keys(data.styles).length, 'merges:', data.sheets[data.sheetOrder[0]].mergeData.length);
const { url, close } = await serve(here);
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1200, height: 800 } });
const errors = []; page.on('pageerror', e => errors.push(String(e))); page.on('console', m => { if (m.type() === 'error') errors.push(m.text().slice(0, 200)); });
await page.goto(`${url}/univer.html`);
await page.waitForFunction(() => typeof window.univerLoad === 'function', null, { timeout: 30000 });
await page.evaluate(d => window.univerLoad(d), data);
await page.waitForTimeout(1500);
console.log('D6 (SUM of formulas) computed:', await page.evaluate(() => window.univerRead('Sales', 'D6')));
console.log('Notes!A2 (cross-sheet formula):', await page.evaluate(() => window.univerRead('Notes', 'A2')));
await page.evaluate(() => window.univerSet('Sales', 'B2', 30));
await page.waitForTimeout(800);
console.log('after edit B2=30, D6 recomputed:', await page.evaluate(() => window.univerRead('Sales', 'D6')));
await page.screenshot({ path: here + 'univer.png' });
const snap = await page.evaluate(() => window.univerSnapshot());
console.log('errors:', errors.length ? errors.slice(0, 5) : 'none');
await browser.close(); close();
const wb = await fromUniver(snap);
const out = await wb.xlsx.writeBuffer(); fs.writeFileSync(here + 'roundtrip.xlsx', Buffer.from(out));
const back = new ExcelJS.Workbook(); await back.xlsx.load(out);
const s = back.getWorksheet('Sales');
console.log('roundtrip: D6 formula', JSON.stringify(s.getCell('D6').value), 'numFmt', s.getCell('D6').numFmt, 'A1 bold', s.getCell('A1').font?.bold, 'A1 fill', s.getCell('A1').fill?.fgColor?.argb, 'A8 merged', s.getCell('B8').isMerged, 'col A width', s.getColumn(1).width, 'B2 validation kept', !!s.getCell('B2').dataValidation, 'A9 date', JSON.stringify(s.getCell('A9').value), 'B9 bool', s.getCell('B9').value, 'sheets', back.worksheets.map(w => w.name));
